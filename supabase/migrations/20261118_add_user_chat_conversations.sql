create table if not exists public.chat_conversations (
  id uuid primary key default gen_random_uuid(),
  user_id text not null,
  title text not null default 'Percakapan baru',
  conversation_date date not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_chat_conversations_user_date
  on public.chat_conversations (user_id, conversation_date desc, created_at desc);

create table if not exists public.app_admin_users (
  email text primary key,
  invited_by text,
  created_at timestamptz not null default now(),
  constraint app_admin_users_email_normalized check (email = lower(trim(email)))
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  user_id text,
  conversation_id uuid,
  role text not null check (role in ('user', 'assistant')),
  content text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.chat_messages
  add column if not exists user_id text,
  add column if not exists conversation_id uuid,
  add column if not exists metadata jsonb not null default '{}'::jsonb;

with legacy_conversations as (
  insert into public.chat_conversations (user_id, title, conversation_date)
  select distinct
    messages.user_id,
    'Riwayat sebelumnya',
    (messages.created_at at time zone 'Asia/Jakarta')::date
  from public.chat_messages as messages
  where messages.user_id is not null
    and messages.conversation_id is null
  returning id, user_id, conversation_date
)
update public.chat_messages as messages
set conversation_id = legacy.id
from legacy_conversations as legacy
where messages.user_id = legacy.user_id
  and (messages.created_at at time zone 'Asia/Jakarta')::date = legacy.conversation_date
  and messages.conversation_id is null;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'chat_messages_conversation_id_fkey'
      and conrelid = 'public.chat_messages'::regclass
  ) then
    alter table public.chat_messages
      add constraint chat_messages_conversation_id_fkey
      foreign key (conversation_id)
      references public.chat_conversations (id)
      on delete cascade;
  end if;
end $$;

create index if not exists idx_chat_messages_user_conversation_created
  on public.chat_messages (user_id, conversation_id, created_at);

alter table public.chat_conversations enable row level security;
alter table public.chat_messages enable row level security;
alter table public.app_admin_users enable row level security;

revoke all on public.chat_conversations, public.chat_messages, public.app_admin_users
  from anon, authenticated;
grant all on public.chat_conversations, public.chat_messages, public.app_admin_users
  to service_role;

do $$
declare
  chat_message_sequence regclass;
begin
  chat_message_sequence := pg_get_serial_sequence('public.chat_messages', 'id');
  if chat_message_sequence is not null then
    execute format('grant usage, select on sequence %s to service_role', chat_message_sequence);
  end if;
end $$;
